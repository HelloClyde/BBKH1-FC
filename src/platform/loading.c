static void rect(unsigned x, unsigned y, unsigned w, unsigned h, uint16_t color)
{
    for (unsigned row=y;row<y+h;++row)
        for (unsigned col=x;col<x+w;++col) canvas[row*480+col]=color;
}
static void text(const char *s,unsigned x,unsigned y,unsigned scale,uint16_t color)
{
    for (;*s;++s,x+=6*scale) {
        int index=*s>='A'&&*s<='Z'?*s-'A':*s>='0'&&*s<='9'?26+*s-'0':*s=='%'?36:-1;
        if (index<0) continue;
        for (unsigned col=0;col<5;++col) for (unsigned row=0;row<7;++row)
            if (glyphs[index][col]&(1u<<row)) rect(x+col*scale,y+row*scale,scale,scale,color);
    }
}
int h1_loading_active(void) { return canvas!=0; }
void h1_loading_step(unsigned percent,const char *stage)
{
    char label[48];
    if (!canvas) return;
    if (percent>100) percent=100;
    if (percent<progress) percent=progress;
    progress=percent;
    rect(0,0,480,272,0x0843);text("LOADING",178,80,3,0xffff);
    rect(48,126,384,24,0x3187);rect(50,128,380,20,0x1084);
    rect(50,128,380*percent/100,20,0x05b4);
    snprintf(label,sizeof label,"%s  %u%%",stage,percent);
    text(label,(480-(unsigned)strlen(label)*12)/2,170,2,0xbdf7);
    gba_game_present(canvas,0);last_tick=h1_raw_tick_80hz();
}
void h1_loading_begin(uint16_t *screen)
{
    canvas=screen;progress=0;total=0;h1_loading_step(3,"PREPARING");
}
void h1_loading_size(size_t bytes) { total=bytes; }
void h1_loading_read(size_t position)
{
    if (!canvas||!total) return;
    if (position>total) position=total;
    unsigned next=20+(unsigned)(position*50/total);
    if (next>progress && (position==total || (unsigned)(h1_raw_tick_80hz()-last_tick)>=10))
        h1_loading_step(next,"READING ROM");
}
void h1_loading_end(void) { canvas=0; }
