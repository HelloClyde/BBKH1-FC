"""Verify pinned dependencies in either a Git clone or a release source ZIP."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def check_dependency(repository: Path, expected: str) -> None:
    repository = repository.resolve()
    if not repository.is_dir():
        raise RuntimeError(f"Missing dependency: {repository}; initialize the Git submodules")
    if (repository / ".git").exists():
        actual = subprocess.check_output(["git", "-C", str(repository), "rev-parse", "HEAD"],
                                         text=True).strip()
        if actual != expected:
            raise RuntimeError(f"Dependency revision mismatch: {repository}: {actual}; expected {expected}")
        changed = subprocess.check_output(["git", "-C", str(repository), "status", "--porcelain"],
                                          text=True).strip()
        if changed:
            raise RuntimeError(f"Dependency checkout is modified: {repository}\n{changed}")
        return

    manifest_path = ROOT / "source-manifest.json"
    if not manifest_path.is_file():
        raise RuntimeError(f"Dependency has neither Git metadata nor a release source manifest: {repository}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    relative = repository.relative_to(ROOT).as_posix()
    if manifest.get("dependencies", {}).get(relative) != expected:
        raise RuntimeError(f"Source manifest does not pin {relative} to {expected}")
    prefix = relative + "/"
    entries = {name: digest for name, digest in manifest.get("files", {}).items()
               if name.startswith(prefix)}
    if not entries:
        raise RuntimeError(f"Source manifest has no files for {relative}")
    for name, digest in entries.items():
        path = (ROOT / name).resolve()
        if not path.is_relative_to(repository) or not path.is_file():
            raise RuntimeError(f"Missing or invalid dependency file: {name}")
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise RuntimeError(f"Dependency file differs from release source manifest: {name}")
    # Reject additional C sources that could otherwise be picked up by glob.
    # Python bytecode is the only file generated by importing the SDK tools.
    for path in repository.rglob("*"):
        if path.is_file() and "__pycache__" not in path.parts:
            name = path.relative_to(ROOT).as_posix()
            if name not in entries:
                raise RuntimeError(f"Unexpected dependency file: {name}")
