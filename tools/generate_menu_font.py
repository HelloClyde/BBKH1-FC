"""Regenerate the checked-in menu glyphs from pinned Noto Sans CJK SC (OFL 1.1)."""
import argparse
import hashlib
import math
from pathlib import Path
from urllib.request import urlopen

import PIL
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT_COMMIT = "f8d157532fbfaeda587e826d4cd5b21a49186f7c"
FONT_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"
FONT_URL = (f"https://raw.githubusercontent.com/notofonts/noto-cjk/{FONT_COMMIT}/"
            "Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf")
PILLOW_VERSION = "12.3.0"


def render(font_path):
    font = ImageFont.truetype(str(font_path), 18)
    source = "".join(path.read_text(encoding="utf-8")
                     for path in sorted((ROOT / "src/platform").glob("*.c")))
    chars = sorted(set(map(chr, range(32, 127))) | {c for c in source if ord(c) >= 128})
    out = ["/* Noto Sans CJK SC rendered glyph subset; OFL 1.1.",
           " * Copyright (c) 2014-2021 Adobe (http://www.adobe.com/).",
           " * See assets/licenses/NotoSansCJK-OFL.txt and assets/README.md.",
           " * Generated by tools/generate_menu_font.py; 18 px, baseline 16. */",
           "#ifndef H1_MENU_FONT_H", "#define H1_MENU_FONT_H",
           "static const struct { uint32_t code, advance, rows[21]; } menu_glyphs[] = {"]
    for char in chars:
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        origin_x = max(0, -left)
        baseline = 16
        if top + baseline < 0 or bottom + baseline > 21 or right + origin_x > 18:
            raise ValueError(f"Glyph U+{ord(char):04X} does not fit the menu cell")
        advance = math.ceil(font.getlength(char)) + origin_x + 1 if ord(char) < 128 else 20
        bitmap = Image.new("L", (18, 21))
        ImageDraw.Draw(bitmap).text((origin_x, baseline), char, font=font, fill=255, anchor="ls")
        rows = [sum(1 << x for x in range(18) if bitmap.getpixel((x, y)) >= 96)
                for y in range(21)]
        out.append("{%d,%d,{%s}}," % (ord(char), advance, ",".join("0x%x" % v for v in rows)))
    out += ["};", "#define MENU_GLYPH_COUNT (sizeof menu_glyphs/sizeof menu_glyphs[0])", "#endif"]
    return ("\n".join(out) + "\n").encode("utf-8"), len(chars)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, help="Pinned OTF; otherwise download it into build/font-cache")
    parser.add_argument("--check", action="store_true", help="Verify the generated header without changing it")
    args = parser.parse_args()
    if PIL.__version__ != PILLOW_VERSION:
        raise SystemExit(f"Font regeneration requires Pillow=={PILLOW_VERSION}; found {PIL.__version__}")
    font_path = args.font or ROOT / "build/font-cache/NotoSansCJKsc-Regular.otf"
    if not font_path.exists() and args.font is None:
        with urlopen(FONT_URL, timeout=60) as response:
            data = response.read()
        if hashlib.sha256(data).hexdigest() != FONT_SHA256:
            raise SystemExit("Downloaded font checksum mismatch")
        font_path.parent.mkdir(parents=True, exist_ok=True)
        font_path.write_bytes(data)
    if hashlib.sha256(font_path.read_bytes()).hexdigest() != FONT_SHA256:
        raise SystemExit("Wrong font revision: SHA-256 mismatch")
    data, count = render(font_path)
    output = ROOT / "src/platform/menu_font.h"
    if args.check:
        if output.read_bytes() != data:
            raise SystemExit("menu_font.h differs; run tools/generate_menu_font.py to regenerate")
    else:
        output.write_bytes(data)
    print(f"{'Verified' if args.check else 'Generated'} {count} glyphs; font SHA-256 {FONT_SHA256}")


if __name__ == "__main__":
    main()
